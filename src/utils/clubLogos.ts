const norm = (s: string) =>
  s
    ? s
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLowerCase()
        .replace(/[^a-z0-9]/g, '')
    : '';

// Mapa normalizado O(1) para busca de escudos sem falsos positivos
const NORMALIZED_CLUB_LOGOS = new Map<string, string>();
for (const [key, url] of Object.entries(CLUB_LOGOS)) {
  NORMALIZED_CLUB_LOGOS.set(norm(key), url);
}

export function getClubLogoUrl(clubName: string): string {
  if (!clubName) return '';
  // 1. Busca exata por chave original
  if (CLUB_LOGOS[clubName]) return CLUB_LOGOS[clubName];

  // 2. Busca exata normalizada (sem acentos e em minúsculas - nunca substring)
  const targetNorm = norm(clubName);
  if (NORMALIZED_CLUB_LOGOS.has(targetNorm)) {
    return NORMALIZED_CLUB_LOGOS.get(targetNorm)!;
  }

  // 3. Fallback seguro: string vazia para ativar o badge com as 3 iniciais do clube
  return '';
}
