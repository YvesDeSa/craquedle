const strip = (s: string) => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase();

export function getCountryFlagUrl(nationality: string): string {
  if (!nationality) return 'https://flagcdn.com/w40/br.png';
  const code = COUNTRY_FLAG_MAP[strip(nationality)] || 'br';
  return `https://flagcdn.com/w40/${code}.png`;
}
